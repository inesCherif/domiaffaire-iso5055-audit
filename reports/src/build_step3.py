def write_csv(rows):
    head = list(rows[0].keys())
    for r in rows:
        if r["id"] in V:
            r["verdict_B"], r["iso_cwe_B"] = V[r["id"]][0], V[r["id"]][1]
    for n in NEW:
        rows.append({"id": n[0], "characteristic": n[1], "severity": "", "confidence": "Medium" if n[0] in ("N03", "N17") else "High",
                     "title": n[2], "location": n[3], "cwe_A": "", "in_iso5055_guess_A": "", "origin": "review B (ISO checklist)",
                     "explanation": n[6], "fix": "", "found_A": "no", "verdict_B": OK if n[5] else PART, "iso_cwe_B": n[4],
                     "found_CAST": "", "found_Sonar": ""})
    with open(ROOT / "findings.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=head)
        w.writeheader()
        w.writerows(rows)


def stats(rows_a):
    c = Counter(V[r["id"]][0] for r in rows_a)
    by_char = {ch: Counter(V[r["id"]][0] for r in rows_a if r["characteristic"] == ch) for ch in (S, R, P, M)}
    crit = [r for r in rows_a if r["severity"] == "Critical"]
    crit_ok = [r["id"] for r in crit if V[r["id"]][0] != NO]
    return c, by_char, crit, crit_ok


